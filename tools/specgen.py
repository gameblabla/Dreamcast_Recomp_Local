#!/usr/bin/env python3
"""specgen.py: generate a STRONG autodiff spec + wrapper skeleton for one retail function from its asm, so the spec is never hand-weakened. Stdlib only.

  python3 -I tools/specgen.py 0x8c073f72 [--out port/tests] [--port port/fn_8c073f72.c] [--include port]

Writes <out>/spec_<addr>.json and <out>/wrapper_<addr>.c (a skeleton with TODOs; it will not compile until you finish it - on purpose).
What the generator decides from the asm (tools/dcfacts.py), instead of the model guessing:
  args      every parameter read before written -> "auto" (boundary values: compared immediates and small constants +-1, 0, -1, random words);
            float parameters -> a list of IEEE bit patterns (0, 1, -1, 2, large, tiny, random)
  regions   every data address loaded from the literal pool -> a region (>= 4 KiB; >= 8 strides when a stride/size constant like 0x630 is loaded;
            large enough for the highest struct offset seen), filled with varied "edge" bytes (never all zero), merged when they would overlap
  callees   every call, TAIL calls with "ints": 4 (the callee gets the caller's r4-r7), floats from the registers set before the call
  check_ret from the return-value heuristic
The result is a starting point that already passes the spec lint; weaken nothing, only ADD (word_choice/patch for the exact values a branch needs).
"""
import argparse, json, os, re, sys

HERE = os.path.dirname(os.path.realpath(__file__))
sys.path.insert(0, HERE)
import dcfacts

MAXEL = 8          # elements per strided table in generated regions
FLOATS = [0x00000000, 0x3f800000, 0xbf800000, 0x40000000, 0x47000000, 0xc7000000, 0x3f000000, 0x7f7fffff, 0x00800000, 0x42c80000, 0xc2c80000, 0x3dcccccd]


def regions_for(f):
    strides = [c['value'] for c in f['consts'] if c['kind'] == 'literal-pool' and 0x100 <= c['value'] <= 0x4000]
    maxoff = max([o for offs in f['offsets'].values() for o in offs] + [c['value'] for c in f['consts'] if c['kind'] == 'imm' and c['value'] < 0x400] + [0])
    stride = max(strides) if strides else 0
    ln = max(4096, (stride * MAXEL if stride else 0) + maxoff + 16)
    ln = (ln + 15) & ~15
    out = []
    for d in sorted(f['data']):
        if out and d < out[-1]['_end']:
            out[-1]['_end'] = max(out[-1]['_end'], d + ln)
            continue
        out.append(dict(_start=d, _end=d + ln))
    regs = []
    for o in out:
        regs.append({'addr': '%08x' % o['_start'], 'len': o['_end'] - o['_start'], 'fill': 'edge'})
    return regs, stride


def dcfacts_callee(addr):
    """registers the callee reads before writing (its own parameters) or None when its asm is not available."""
    try:
        return set(dcfacts.facts(addr)['params'])
    except Exception:
        return None


def port_skeleton(h, f, pc, args, ptr_args, callees, stack_words):
    L = ['/* Port of retail function 0x%s. SKELETON generated by tools/specgen.py from the asm: inputs, constants and callee helpers are filled in, the BODY is yours.' % h,
         ' * Everything below marked "from the asm" is a fact read by tools; names and meanings are HYPOTHESES until `autodiff.py SPEC --final` prints RESULT: PROVEN. */',
         '#include "autodiff.h"', '#include <stddef.h>', '#include <stdint.h>', '']
    L.append('/* INPUTS (from the asm)')
    for p in f['params']:
        if p in ptr_args:
            v = ptr_args[p]
            L.append(' *   %-4s pointer, field offsets %s, %s%s  -> ad_rd32/ad_rd16s/ad_rd8/ad_wr32(c->r[%s] + off)' % (p, [hex(o) for o in v['offsets']], 'written' if v['written'] else 'read-only', ', null-checked' if v['null_check'] else '', p[1:]))
        elif p.startswith('fr'):
            L.append(' *   %-4s float argument (raw IEEE bits in c->fr[%s])' % (p, p[2:]))
        else:
            L.append(' *   %-4s scalar%s%s' % (p, ' (loop COUNT candidate)' if p in pc['count'] else '', ' (INDEX: scaled / added to a table base)' if p in pc.get('index', []) else ''))
    for i in pc['stack_args']:
        v = ptr_args.get('stack%d' % i)
        L.append(' *   stack arg %d (5th+ argument) at AD_STACK_TOP + %d: %s -> ad_rd32(c->r[15] + %d)' % (i, 4 * i, ('pointer, field offsets %s' % [hex(o) for o in v['offsets']]) if v else ('INDEX (scaled, added to a table base)' if 'S%d' % i in pc.get('index', []) else 'scalar'), 4 * i))
    L.append(' *   returns: %s */' % {'value': 'a value: set c->ret', 'float': 'a float in fr0: set c->ret to its bits', 'void': 'nothing'}.get(f['returns'], f['returns']))
    L.append('')
    pool = [c for c in f['consts'] if c['kind'] == 'literal-pool']
    flt = re.findall(r'; => (fr\d+) = (\S+) \((0x[0-9a-f]+)\) \[literal at ([0-9a-f]+)\]', f['text'])
    if pool or flt:
        L.append('/* CONSTANTS loaded from the literal pool (from the asm; use them, never "similar" numbers from other functions) */')
        seen = set()
        for c in pool:
            if c['value'] in seen:
                continue
            seen.add(c['value'])
            L.append('#define K_%08X_%s 0x%xu   /* %d, loaded into %s at %08x */' % (c['addr'], c['reg'].upper(), c['value'], c['value'] - (1 << 32) if c['value'] >> 31 else c['value'], c['reg'], c['addr']))
        for reg, val, bits, at in flt:
            L.append('#define KF_%s_%s %su   /* float %s (IEEE bits), literal at %s */' % (at.upper(), reg.upper(), bits, val, at))
        L.append('')
    for c in callees:
        call = [x for x in f['calls'] if c['addr'] == '%08x' % (x['target'] or 0)][0]
        ni, nf = c['ints'], c['floats']
        params = ['uint32_t a%d' % k for k in range(ni)] + ['uint32_t f%d' % k for k in range(nf)]
        L.append('/* callee %s%s%s: the call is reported with %d int + %d float argument register(s); autodiff compares them and returns the scripted r0 */' % (c['addr'], ' (' + call['name'] + ')' if call.get('name') else '', ' TAIL CALL: report it LAST and return nothing after it' if call['tail'] else '', ni, nf))
        L.append('static uint32_t call_%s(%s)' % (c['addr'], ', '.join(params) or 'void'))
        L.append('{')
        L.append('    const uint32_t ints[%d] = {%s};' % (max(ni, 1), ', '.join('a%d' % k for k in range(ni)) or '0'))
        L.append('    const uint32_t fl[%d] = {%s};' % (max(nf, 1), ', '.join('f%d' % k for k in range(nf)) or '0'))
        L.append('    return ad_call(0x%s, ints, %d, fl, %d);' % (c['addr'], ni, nf))
        L.append('}')
        L.append('')
    L.append('void fn_%s(ad_regs *c)' % h)
    L.append('{')
    for p in f['params']:
        if p.startswith('fr'):
            L.append('    uint32_t %s = c->fr[%s];   /* IEEE bits */' % (p, p[2:]))
        else:
            L.append('    uint32_t %s = c->r[%s];' % (p, p[1:]))
    for i in pc['stack_args']:
        L.append('    uint32_t stack%d = ad_rd32(c->r[15] + %d);   /* stack argument %d */' % (i, 4 * i, i))
    L.append('    (void)c;')
    L.append('')
    L.append('    /* TODO: translate the annotated asm (./dcre annotate 0x%s) block by block. Keep the compare kinds (signed cmp/ge,gt vs unsigned cmp/hs,hi), widths and the call order. */' % h)
    L.append('    #error "port not written"')
    L.append('}')
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('addr'); ap.add_argument('--out', default='port/tests'); ap.add_argument('--port'); ap.add_argument('--include', default='port')
    ap.add_argument('--cases', type=int, default=150)
    a = ap.parse_args()
    addr = int(a.addr, 16)
    f = dcfacts.facts(addr)
    h = '%08x' % addr
    port = a.port or 'port/fn_%s.c' % h
    regs, stride = regions_for(f)
    args = {}
    for p in f['params']:
        args[p] = 'auto' if p.startswith('r') else FLOATS
    if any(c['tail'] for c in f['calls']):       # a tail callee receives the caller's r4-r7: they must vary too, whether or not this function reads them
        for r in ('r4', 'r5', 'r6', 'r7'):
            args.setdefault(r, 'auto')
    callees, seen = [], {}
    for c in f['calls']:
        if c['target'] is None:
            continue
        t = '%08x' % c['target']
        reads = dcfacts_callee(c['target'])
        ni = (4 if reads is None else max([int(r[1:]) - 3 for r in reads if re.fullmatch(r'r[4-7]', r)] or [0])) if c['tail'] else max([int(k[1:]) - 3 for k in c['args'] if re.fullmatch(r'r[4-7]', k) and not c['args'][k].startswith(('(inherited)', '(set on SOME'))] or [0])
        nf = max([int(k[2:]) - 3 for k in c['args'] if re.fullmatch(r'fr(4|5|6|7|8|9|10|11)', k)] or [0])
        if c['tail'] and reads is not None:
            nf = max([int(r[2:]) - 3 for r in reads if re.fullmatch(r'fr[4-9]|fr1[01]', r)] or [0])
        cur = seen.get(t)
        if cur:
            cur['ints'], cur['floats'] = max(cur['ints'], ni), max(cur['floats'], nf)
        else:
            e = {'addr': t, 'ints': ni, 'floats': nf}
            seen[t] = e; callees.append(e)
    if stride:
        # indexes into a table of `stride`-byte elements must stay inside the region (retail would read arbitrary RAM, the wrapper aborts)
        for k, v in args.items():
            pass
    for sl in f.get('scaled_loads', []):
        if sl['field_off'] is None:
            continue
        for r in regs:        # bound the INDEX field (read as s16, scaled by sl['scale']) inside every element of every strided region
            room = max(l['len'] for l in regs if l is not r) if len(regs) > 1 else r['len']
            top = max(1, min(7, room // sl['scale'] - 2))
            if stride:
                r.setdefault('patch', [])
                for kk in range(r['len'] // stride):
                    r['patch'].append({'off': kk * stride + sl['field_off'], 'len': 1, 'choice': list(range(0, top + 1))})     # s16 index: low byte small,
                    r['patch'].append({'off': kk * stride + sl['field_off'] + 1, 'len': 1, 'choice': [0]})                    # high byte 0 (patch bytes are independent)
    # ---- parameter classes from the asm: pointers get their own regions, stack arguments a stack region, loop counts a sane range
    pc = dict(ptr={}, stack_args=[], stack_ptr={}, count=[])
    try:
        pc = dcfacts.param_classes(f['text'])
    except Exception as ex:
        print('note: parameter classification skipped: %s' % ex)

    def free_base(size):
        b = 0x8cf00000
        while any(b < int(r['addr'], 16) + r['len'] and b + size > int(r['addr'], 16) for r in regs):
            b += 0x2000
        return b
    ptr_args, ptr_info = {}, {}
    for p_, e in sorted(pc['ptr'].items()):
        if p_ not in args:
            continue
        size = max(256, (max(e['off'] or [0]) + 64 + 255) & ~255)
        b = free_base(size)
        regs.append({'addr': '%08x' % b, 'len': size, 'fill': 'edge'})
        args[p_] = [b] + ([0] if e['null_check'] else [])
        ptr_args[p_] = dict(base='%08x' % b, size=size, offsets=e['off'], written=e['writes'], null_check=e['null_check'])
        ptr_info[p_] = b
    stack_words = (max(pc['stack_args']) + 1) if pc['stack_args'] else 0
    if stack_words:
        sregs = {'addr': '8cffff00', 'len': max(64, (stack_words * 4 + 31) & ~31), 'fill': 'edge', 'patch': []}
        for idx, e in sorted(pc['stack_ptr'].items()):
            size = max(256, (max(e['off'] or [0]) + 64 + 255) & ~255)
            b = free_base(size)
            regs.append({'addr': '%08x' % b, 'len': size, 'fill': 'edge'})
            for j in range(4):
                sregs['patch'].append({'off': idx * 4 + j, 'len': 1, 'choice': [(b >> (8 * j)) & 0xff]})
            ptr_args['stack%d' % idx] = dict(base='%08x' % b, size=size, offsets=e['off'], written=e['writes'], null_check=e['null_check'])
        for pidx in pc.get('index', []):                  # stack argument used as an INDEX: small values, or the retail table read leaves every region
            if isinstance(pidx, str) and pidx.startswith('S'):
                top = (MAXEL - 1) if stride else 40
                i_ = int(pidx[1:])
                sregs['patch'].append({'off': i_ * 4, 'len': 1, 'choice': list(range(0, top + 1))})
                for j in (1, 2, 3):
                    sregs['patch'].append({'off': i_ * 4 + j, 'len': 1, 'choice': [0]})
        if not sregs['patch']:
            del sregs['patch']
        regs.append(sregs)
    limits = {p_: [-2, 40] for p_ in pc['count'] if args.get(p_) == 'auto'}
    for p_ in pc.get('index', []):
        if isinstance(p_, str) and p_.startswith('r') and args.get(p_) == 'auto' and p_ not in limits:
            limits[p_] = [-2, MAXEL - 1] if stride else [-2, 40]      # a table index / scaled value: values far outside the table only fault
    if ptr_args or stack_words or limits:
        print('PARAMETER CLASSES (from the asm; HYPOTHESIS until the port is proven):')
        for k, v in ptr_args.items():
            print('   %-7s pointer, base %s (%d bytes), field offsets %s%s%s' % (k, v['base'], v['size'], [hex(o) for o in v['offsets']], ', WRITTEN' if v['written'] else ', read-only', ', null-checked' if v['null_check'] else ''))
        if stack_words:
            print('   stack arguments: %d word(s) at [sp+4*i] (i = %s), region 8cffff00 (port: ad_rd32(AD_STACK_TOP + 4*i))' % (stack_words, pc['stack_args']))
        if limits:
            print('   "arg_limits" %s for count/index parameter(s) %s (huge counts run for ever, huge indexes leave the table); widen by hand if the real domain is larger' % (limits, ', '.join(sorted(limits))))
        if pc.get('index'):
            print('   INDEX/scaled values (shifted, multiplied or added to a table base): %s' % ', '.join(map(str, pc['index'])))
    spec = {'func': h, 'cases': a.cases, 'seed': 1, 'check_ret': f['returns'] == 'value',
            'port': {'wrapper': '%s/wrapper_%s.c' % (a.out, h), 'sources': [port], 'include': [a.include]},
            'args': args, 'regions': regs, 'callees': callees,
            'notes': 'generated by tools/specgen.py: only ADD to it (never remove args/regions/callee registers; autodiff keeps a ledger and rejects a weaker spec)'}
    if stride:
        spec['auto_range'] = [-2, MAXEL - 1]
    spec['write_trace'] = True       # compare the retail store SEQUENCE (order, count, width, value) with the port's ad_wr8/16/32 calls, like Mizuchi's behavioural check
    if ptr_args:
        spec['ptr_args'] = ptr_args
    if stack_words:
        spec['stack_args'] = stack_words
    if limits:
        spec['arg_limits'] = limits
    os.makedirs(a.out, exist_ok=True)
    sp = os.path.join(a.out, 'spec_%s.json' % h)
    if os.path.exists(sp):
        sys.exit('%s exists: refusing to overwrite (it may be strengthened already). Delete it by hand to regenerate.' % sp)
    json.dump(spec, open(sp, 'w'), indent=1)
    w = ['/* wrapper skeleton for retail %s, generated by tools/specgen.py. Finish it, then run:  AD_SANITIZE=1 ./dcre autodiff %s --mutate' % (h, sp),
         ' * Rules: pass the retail arguments exactly as the asm shows (see ./dcre annotate 0x%s); report EVERY stubbed call with ad_call(), in order,' % h,
         ' * with all the argument registers listed below; tail calls: report the tail callee LAST and return nothing after it. */',
         '#include "autodiff.h"', '/* #include "%s" */' % os.path.basename(port).replace('.c', '.h'), '']
    for c in callees:
        call = [x for x in f['calls'] if c['addr'] == '%08x' % (x['target'] or 0)][0]
        w.append('/* callee %s%s: compare ints=%d floats=%d. Registers at the call:' % (c['addr'], ' (TAIL CALL)' if call['tail'] else '', c['ints'], c['floats']))
        for k, v in call['args'].items():
            w.append(' *    %-4s = %s' % (k, v))
        w.append(' */')
        w.append('static void report_%s(const uint32_t *ints /* %d */, const uint32_t *floats /* %d */)\n{\n    /* ad_call(0x%s, ints, %d, floats, %d); */\n}\n' % (c['addr'], c['ints'], c['floats'], c['addr'], c['ints'], c['floats']))
    wp = os.path.join(a.out, 'wrapper_%s.c' % h)
    if not os.path.exists(wp):
        open(wp, 'w').write('/* wrapper for retail %s (generated, complete: the port takes the register file directly and reports callee calls itself via ad_call) */\n'
                            '#include "autodiff.h"\n\nextern void fn_%s(ad_regs *c);\n\nvoid ad_wrapper(ad_regs *c)\n{\n    fn_%s(c);\n}\n' % (h, h, h))
    if not os.path.exists(port):
        os.makedirs(os.path.dirname(port) or '.', exist_ok=True)
        open(port, 'w').write(port_skeleton(h, f, pc, args, ptr_args, callees, stack_words))
        print('wrote port skeleton %s (fill in the body; the #error line is removed when you are done)' % port)
    print('wrote %s and %s' % (sp, wp))
    print('params=%s returns=%s regions=%s callees=%s' % (f['params'], f['returns'], [(r['addr'], r['len']) for r in regs], [(c['addr'], c['ints'], c['floats']) for c in callees]))
    if stride:
        print('stride/size constant 0x%x detected: regions hold >= 8 elements; give the index argument small values via "auto" or a list like [0,1,2,3,7]' % stride)


if __name__ == '__main__':
    main()
