// offline test of the dcguard plugin core: node tests/test_dcguard.mjs
import fs from "node:fs"; import os from "node:os"; import path from "node:path";
import { Guard } from "../.opencode/dcguard/core.mjs";
let fails = 0;
const ok = (n, c, i = "") => { console.log((c ? "ok    " : "FAIL  ") + "dcguard: " + n + (c ? "" : "  " + i)); if (!c) fails++; };
const d = fs.mkdtempSync(path.join(os.tmpdir(), "dcg-"));
for (const x of ["tools/dc", "port/tests", "work/notes", ".agents/skills/decomp-function"]) fs.mkdirSync(path.join(d, x), { recursive: true });
for (const t of ["autodiff.py", "readmem.py", "notes.py"]) fs.writeFileSync(path.join(d, "tools/dc", t), "#");
fs.writeFileSync(path.join(d, "AGENTS.md"), "# t\n\n## Headless local-model runs\n- RULE-HEADLESS-MARKER\n\n## Model policy\n- not for the local model\n");
fs.writeFileSync(path.join(d, ".agents/skills/decomp-function/SKILL.md"), "SKILL-MARKER");
fs.writeFileSync(path.join(d, "work/notes/fn_8c043680.md"), "- [FACT] div_s32 dividend r1 NOTE-MARKER\n");
const g = new Guard(d, { DC_AGENT: "1", DC_AGENT_ADDR: "0x8c043680" });
const p = g.pinned();
ok("pinned has headless rules, skill and notes", p.includes("RULE-HEADLESS-MARKER") && p.includes("SKILL-MARKER") && p.includes("NOTE-MARKER"), p.slice(0, 300));
ok("pinned leaves out unrelated sections", !p.includes("not for the local model"));
ok("compaction note keeps notes verbatim", g.compactionNote().includes("VERBATIM"));
const sh = (c) => g.before("shell", { command: c });
ok("nonexistent tool script blocked, real ones listed", /does not exist.*autodiff\.py/.test(sh("python3 -I tools/dc/dcre.py disasm 0x1") || ""));
ok("existing tool allowed", sh("python3 -I tools/dc/autodiff.py port/tests/spec.json") === null);
ok("AD_ALLOW_WEAKER blocked", /human-only/.test(sh("AD_ALLOW_WEAKER=1 python3 -I tools/dc/autodiff.py x") || ""));
ok("--seed hunting blocked, --final allowed", /seed hunting/.test(sh("python3 -I tools/dc/autodiff.py s.json --seed 3") || "") && sh("python3 -I tools/dc/autodiff.py s.json --final") === null);
ok("--cases 3 blocked, default allowed", /floor/.test(sh("python3 -I tools/dc/autodiff.py s.json --cases 3") || "") && sh("python3 -I tools/dc/autodiff.py s.json --cases 150") === null);
ok("hand-reading the retail image blocked, readmem allowed", /readmem/.test(sh("python3 -c \"open('game/Track_3/1ST_READ.BIN','rb')\"") || "") && sh("python3 -I tools/dc/readmem.py 0x8c04ca18") === null);
ok("proof ledger edits blocked", /append-only/.test(sh("rm -f work/proofs/8c043680.json") || ""));
const cmd = "python3 -I tools/dc/sh4_annotate.py 0x8c043680 | grep 8c0437"; fs.writeFileSync(path.join(d, "tools/dc/sh4_annotate.py"), "#");
const a = [sh(cmd), sh(cmd), sh(cmd)];
ok("third identical command on unchanged files hits the LOOP GUARD", a[0] === null && a[1] === null && /LOOP GUARD/.test(a[2] || ""), JSON.stringify(a));
fs.writeFileSync(path.join(d, "port/fn_8c043680.c"), "int x;");   // a file changed: the same command is legitimate again
ok("same command after an edit is allowed", sh(cmd) === null);
g.after("shell", "usage: autodiff.py"); g.after("shell", "Traceback");
ok("error streak counted and shown in the pinned state", g.errStreak === 2 && g.pinned().includes("consecutive failing calls: 2"));
g.after("shell", "fine");
ok("error streak resets", g.errStreak === 0);
// ---- phase steering (derived from files + ledger, never from model claims)
const d2 = fs.mkdtempSync(path.join(os.tmpdir(), "dcg2-"));
for (const x of ["port/tests", "work/brief", "work/proofs", "tools/dc"]) fs.mkdirSync(path.join(d2, x), { recursive: true });
fs.writeFileSync(path.join(d2, "AGENTS.md"), "## Headless local-model runs\n- x\n");
const g2 = new Guard(d2, { DC_AGENT: "1", DC_AGENT_ADDR: "0x8c043680" });
const ph = () => g2.phase().name;
ok("phase: no brief -> brief", ph() === "brief" && /brief\.py 0x8c043680/.test(g2.phase().next));
fs.writeFileSync(path.join(d2, "work/brief/fn_8c043680.md"), "# Brief\n## INPUTS\n- r7: scalar COUNT\n## FULL ANNOTATED LISTING\nLISTING-MARKER");
ok("phase: brief but no spec -> spec (and the brief summary is pinned without the listing)", ph() === "spec" && g2.pinned().includes("r7: scalar COUNT") && !g2.pinned().includes("LISTING-MARKER"));
fs.writeFileSync(path.join(d2, "port/tests/spec_8c043680.json"), "{}");
fs.writeFileSync(path.join(d2, "port/fn_8c043680.c"), 'void f(){\n#error "port not written"\n}');
ok("phase: skeleton with #error -> write", ph() === "write");
fs.writeFileSync(path.join(d2, "port/fn_8c043680.c"), "void f(){}");
ok("phase: body written, no ledger -> first-run", ph() === "first-run");
const led = (result, extra = {}) => fs.writeFileSync(path.join(d2, "work/proofs/8c043680.json"), JSON.stringify({ runs: [Object.assign({ result, proven: /PROVEN$/.test(result), final: false }, extra)] }));
led("RESULT: NOT PROVEN -- 33 mismatches (x)"); ok("phase: mismatches -> fix-mismatch", ph() === "fix-mismatch");
led("RESULT: NOT PROVEN -- retail instructions never executed"); ok("phase: coverage", ph() === "coverage");
led("RESULT: NOT PROVEN -- mutants survived (strengthen)"); ok("phase: mutants", ph() === "mutants");
led("RESULT: NOT PROVEN -- PORT RUN ABORTED"); ok("phase: loop -> arg_limits advice", ph() === "loop" && /arg_limits/.test(g2.phase().next));
led("RESULT: PROVEN"); ok("phase: provisional PROVEN -> final", ph() === "final");
led("RESULT: PROVEN", { final: true }); ok("phase: FINAL PROVEN -> done", ph() === "done");
g2.sinceAutodiff = 30; led("RESULT: NOT PROVEN -- 3 mismatches"); ok("steering warns after 25 calls without autodiff", /calls since your last autodiff/.test(g2.steering()));
ok("pinned carries PHASE and NEXT ACTION", /PHASE: fix-mismatch/.test(g2.pinned()) && /NEXT ACTION:/.test(g2.pinned()));
// ---- deterministic compaction summary + stall steering
fs.mkdirSync(path.join(d2, "work/notes"), { recursive: true });
fs.writeFileSync(path.join(d2, "work/notes/fn_8c043680.md"), "- [FACT] stack arg 0 is an INDEX NOTE-X\n");
g2.before("shell", { command: "python3 -I tools/dc/autodiff.py s.json" }); g2.after("shell", "usage: autodiff.py: error");
const sm = g2.summary();
ok("compaction summary has notes verbatim, failing command with its error, history, task", sm.includes("NOTE-X") && sm.includes("Last failing commands") && sm.includes("autodiff.py s.json") && sm.includes("Task: port retail function 0x8c043680") && sm.includes("PHASE:"), sm.slice(0, 400));
const mk = (n) => fs.writeFileSync(path.join(d2, "work/proofs/8c043680.json"), JSON.stringify({ runs: n.map((m) => ({ result: `RESULT: NOT PROVEN -- ${m} mismatches (x)`, proven: false, final: false })) }));
mk([30, 12, 5, 9, 7, 8]);
ok("stalled: 3 runs without beating the best -> restore advice", /STALLED/.test(g2.steering()) && /attempts\.py restore/.test(g2.steering()), g2.steering());
mk([30, 12, 9, 7, 5, 3]);
ok("improving runs are not flagged as stalled", !/STALLED/.test(g2.steering()));
// ---- mizuchi-style budget footer, output cap, hard call limit
process.env.DC_CALL_LIMIT = "5";
const core2 = await import("../.opencode/dcguard/core.mjs?x=" + Date.now());
const g3 = new core2.Guard(d2, { DC_AGENT: "1", DC_AGENT_ADDR: "0x8c043680" });
for (let k = 0; k < 4; k++) g3.before("shell", { command: "echo " + k });
ok("footer shows calls used/limit, phase and next action", /\[dcguard\] calls 4\/5/.test(g3.footer()) && /ONLY 1 LEFT/.test(g3.footer()) && /phase:/.test(g3.footer()), g3.footer());
for (const t of ["autodiff.py", "notes.py"]) fs.writeFileSync(path.join(d2, "tools/dc", t), "#");
const big = "x".repeat(20000) + "TAIL-MARK";
const capped = g3.cap(big);
ok("long output is capped, head and tail kept, hint to narrow", capped.length < 8000 && capped.includes("TAIL-MARK") && /omitted/.test(capped));
ok("short output untouched", g3.cap("short") === "short");
g3.before("shell", { command: "echo 5" });
const lim = g3.before("shell", { command: "ls port" });
ok("beyond the hard limit ordinary commands are blocked with a submit-now message", /Tool call limit reached/.test(lim || ""), String(lim));
ok("beyond the limit autodiff --final and notes.py stay allowed", g3.before("shell", { command: "python3 -I tools/dc/autodiff.py s.json --final" }) === null && g3.before("shell", { command: "python3 -I tools/dc/notes.py show 0x8c043680" }) === null);
console.log(fails ? `${fails} dcguard check(s) FAILED` : "dcguard: all checks passed");
process.exit(fails ? 1 : 0);
